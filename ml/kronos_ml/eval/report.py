"""Evaluate every trained model on the held-out test slice.

    python -m kronos_ml.eval.report                 # metrics + figures
    python -m kronos_ml.eval.report --robustness    # also re-run at 0.5% / 0.1% fraud over 5 seeds

Writes report/results.md, report/results.json and report/figures/*.png.
Each model gets its own High threshold, chosen on validation with the same
business-cost rule used for the deployed model, so the comparison is fair.
"""
from __future__ import annotations

import argparse
import json

import joblib
import numpy as np
import pandas as pd

from ..config import FIGURES_DIR, MODELS_DIR, REPORT_DIR, load_config
from ..features.build import FEATURES
from ..models.train import choose_thresholds, load_features, split
from . import plots
from .metrics import full_report, per_pattern_recall

MODELS = ["zscore_baseline", "isolation_forest", "lof", "ocsvm", "ensemble"]


def evaluate(models_dir=None, data_dir=None) -> dict:
    cfg = load_config()
    md = models_dir or MODELS_DIR
    FIGURES_DIR.mkdir(parents=True, exist_ok=True)
    parts = split(load_features(data_dir), cfg)
    val, test = parts["val"], parts["test"]
    y = test["is_fraud"].to_numpy()
    card = json.loads((md / "model_card.json").read_text())

    dets = {m: joblib.load(md / f"{m}.joblib") for m in MODELS}
    raw = {m: d.raw(test) for m, d in dets.items()}
    rows, patterns, patterns_budget, flags, thr_pct = [], {}, {}, {}, {}
    cost_grids = {}
    for m, d in dets.items():
        medium, high, grid = choose_thresholds(d, val, cfg)
        cost_grids[m] = grid
        r = full_report(y, raw[m], high, test["fraud_type"], test["amount"].to_numpy(), cfg["risk"]["review_cost"])
        rows.append({"model": m, **r})
        patterns[m] = per_pattern_recall(test["fraud_type"], raw[m], high)
        patterns_budget[m] = per_pattern_recall(test["fraud_type"], raw[m], np.quantile(raw[m], 0.98))
        flags[m] = raw[m] >= high
        thr_pct[m] = float((raw[m] < high).mean())
    table = pd.DataFrame(rows).set_index("model")
    pat = pd.DataFrame(patterns).T
    pat_budget = pd.DataFrame(patterns_budget).T

    plots.roc_pr_curves(y, raw, FIGURES_DIR / "roc_pr.png")
    plots.score_histograms(y, raw, thr_pct, FIGURES_DIR / "score_hist.png")
    plots.confusion_grid(y, flags, FIGURES_DIR / "confusion.png")
    plots.pattern_heatmap(pat, "Recall by fraud pattern (each model at its own High threshold)", FIGURES_DIR / "pattern_recall.png")
    plots.pattern_heatmap(pat_budget, "Recall by fraud pattern (top 2% alert budget)", FIGURES_DIR / "pattern_recall_top2.png")
    dep = card["model"]
    g = cost_grids[dep]
    chosen = float(g.loc[g["total_cost"].idxmin(), "alert_rate"])
    plots.cost_curve(g, chosen, FIGURES_DIR / "cost_curve.png")

    # SHAP feature importance for the Isolation Forest.
    try:
        from ..explain import shap_values

        sample = test.sample(min(3000, len(test)), random_state=0)
        sv, _ = shap_values(dets["isolation_forest"], sample)
        imp = pd.Series(np.abs(sv).mean(axis=0), index=FEATURES)
        plots.feature_importance(imp, "Isolation Forest: mean |SHAP| (test sample)", FIGURES_DIR / "shap_importance.png")
        importance = imp.sort_values(ascending=False).round(4).to_dict()
    except Exception as e:  # shap is optional
        print(f"SHAP skipped: {e}")
        importance = {}

    result = {
        "deployed": dep,
        "test_rows": int(len(test)),
        "test_fraud_rate": float(y.mean()),
        "comparison": table.round(4).reset_index().to_dict(orient="records"),
        "pattern_recall": pat.round(3).to_dict(),
        "pattern_recall_top2": pat_budget.round(3).to_dict(),
        "shap_importance": importance,
        "chosen_alert_rate": chosen,
    }
    (REPORT_DIR / "results.json").write_text(json.dumps(result, indent=2, default=float))
    write_markdown(result, table, pat, pat_budget, card)
    return result


def _fmt(df: pd.DataFrame) -> str:
    return df.to_markdown(floatfmt=".3f") if hasattr(df, "to_markdown") else df.to_string()


def write_markdown(result, table, pat, pat_budget, card, robustness: pd.DataFrame | None = None):
    cols = ["roc_auc", "pr_auc", "precision@thr", "recall@thr", "f1@thr", "alert_rate@thr",
            "precision@top2%", "recall@top2%", "missed_fraud_amount", "alerts", "total_cost"]
    t = table[cols].rename(index=plots.LABELS)
    lines = [
        "# Kronos Fraud Shield: evaluation results",
        "",
        f"Generated by `make eval` from `{card['version']}`. Test slice: days 70-90, "
        f"{result['test_rows']:,} transfers, {result['test_fraud_rate']:.2%} fraud.",
        "",
        f"**Deployed model:** {plots.LABELS.get(result['deployed'], result['deployed'])} "
        f"({card['description']}). High band = top {result['chosen_alert_rate']:.1%} of transfers, "
        "picked by minimising missed fraud + review cost on validation.",
        "",
        "## Model comparison (test)",
        "",
        "Threshold metrics use each model's own cost-optimal High threshold from validation.",
        "",
        t.to_markdown(floatfmt=".3f"),
        "",
        "![ROC and PR curves](figures/roc_pr.png)",
        "",
        "## Recall by fraud pattern",
        "",
        "At each model's High threshold:",
        "",
        pat.rename(index=plots.LABELS).to_markdown(floatfmt=".2f"),
        "",
        "With a fixed alert budget (top 2% of transfers):",
        "",
        pat_budget.rename(index=plots.LABELS).to_markdown(floatfmt=".2f"),
        "",
        "![Recall by pattern](figures/pattern_recall.png)",
        "",
        "## Threshold choice",
        "",
        "![Cost curve](figures/cost_curve.png)",
        "",
        "## Score distributions and confusion matrices",
        "",
        "![Score histograms](figures/score_hist.png)",
        "",
        "![Confusion matrices](figures/confusion.png)",
        "",
    ]
    if result.get("shap_importance"):
        top = list(result["shap_importance"].items())[:10]
        lines += ["## What drives the Isolation Forest (SHAP)", "", "| feature | mean abs SHAP |", "|---|---|"]
        lines += [f"| `{k}` | {v:.3f} |" for k, v in top]
        lines += ["", "![SHAP importance](figures/shap_importance.png)", ""]
    rob_path = REPORT_DIR / "robustness.csv"
    if robustness is None and rob_path.exists():
        robustness = pd.read_csv(rob_path)
    if robustness is not None:
        g = robustness.groupby(["fraud_rate", "model"])["pr_auc"].agg(["mean", "std"])
        agg = (g["mean"].map("{:.3f}".format) + " ± " + g["std"].map("{:.3f}".format)).unstack("model")
        agg = agg[[m for m in MODELS if m in agg.columns]].rename(columns=plots.LABELS).sort_index(ascending=False)
        agg.index = [f"{r:.1%}" for r in agg.index]
        agg.index.name = "fraud rate"
        lines += [
            "## Robustness: lower fraud rates and other seeds",
            "",
            "PR-AUC on the test slice, mean ± std over 5 seeds. Smaller dataset (800 users) and the tuned "
            "hyper-parameters of the main run. A random ranker scores PR-AUC equal to the fraud rate.",
            "",
            agg.to_markdown(),
            "",
            "![Robustness](figures/robustness.png)",
            "",
        ]
    (REPORT_DIR / "results.md").write_text("\n".join(lines))


def robustness(seeds=(1, 2, 3, 4, 5), rates=(0.02, 0.005, 0.001), n_users=800) -> pd.DataFrame:
    """Regenerate data at several fraud rates and seeds; retrain with the tuned settings."""
    from sklearn.metrics import average_precision_score, roc_auc_score

    from ..features.build import build_features
    from ..models.ensemble import RankEnsemble
    from ..simulator.generate import build_dataset

    cfg = load_config()
    tuned = {m: joblib.load(MODELS_DIR / f"{m}.joblib") for m in ["zscore_baseline", "isolation_forest", "lof", "ocsvm"]}
    ens_names = [m.name for m in joblib.load(MODELS_DIR / "ensemble.joblib").members]
    rows = []
    for rate in rates:
        for seed in seeds:
            tx, users = build_dataset(seed=seed, n_users=n_users, fraud_rate=rate)
            df = pd.concat([tx, build_features(tx, users)], axis=1)
            parts = split(df, cfg)
            yt = parts["test"]["is_fraud"].to_numpy()
            if yt.sum() < 3:
                continue
            fitted = {}
            for name, d in tuned.items():
                det = type(d)(FEATURES, max_rows=d.max_rows, seed=seed, **d.params).fit(parts["train"])
                fitted[name] = det
            fitted["ensemble"] = RankEnsemble([fitted[n] for n in ens_names], parts["train"].sample(
                min(20000, len(parts["train"])), random_state=0))
            for name, det in fitted.items():
                s = det.raw(parts["test"])
                rows.append({"fraud_rate": rate, "seed": seed, "model": name,
                             "pr_auc": average_precision_score(yt, s), "roc_auc": roc_auc_score(yt, s),
                             "n_fraud_test": int(yt.sum())})
            print(f"rate={rate} seed={seed} done ({int(yt.sum())} fraud in test)")
    df = pd.DataFrame(rows)
    df.to_csv(REPORT_DIR / "robustness.csv", index=False)
    plots.robustness_plot(df, FIGURES_DIR / "robustness.png")
    return df


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--robustness", action="store_true")
    a = ap.parse_args()
    REPORT_DIR.mkdir(exist_ok=True)
    FIGURES_DIR.mkdir(parents=True, exist_ok=True)
    if a.robustness:
        robustness()
    r = evaluate()
    print(pd.DataFrame(r["comparison"]).set_index("model")[["roc_auc", "pr_auc", "precision@thr", "recall@thr", "f1@thr"]].round(3))
    print(pd.DataFrame(r["pattern_recall"]).round(2))


if __name__ == "__main__":
    main()
